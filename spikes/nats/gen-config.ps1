# Generates the spike nats-server config from public NKeys in .spikes/nats/keys/.
# Usage: powershell -NoProfile -File spikes/nats/gen-config.ps1 [-Out <path>] [-MaxPayload <bytes>]
# Output contains public NKeys only (RFC-0010 [0010-009]); never seeds.
param(
  [string]$Out = "",
  [int]$MaxPayload = 1048576
)
$ErrorActionPreference = "Stop"
$repo = (Resolve-Path (Join-Path $PSScriptRoot "../..")).Path
$spike = Join-Path $repo ".spikes/nats"
$keys = Join-Path $spike "keys"
if (-not $Out) { $Out = Join-Path $spike "nats.conf" }
$store = (Join-Path $spike "data") -replace '\\', '/'
function Pub([string]$id) { (Get-Content -Raw (Join-Path $keys "$id.pub")).Trim() }

# Read bundle per stream (RFC-0010 [0010-059]); the spike shrinks/extends it from violation logs.
$readStreams = @("A2AB_EV_local", "KV_a2ab-local-cards", "KV_a2ab-local-presence", "KV_a2ab-local-claims", "OBJ_a2ab-local-artifacts")
function ReadBundle([string]$s) {
  @(
    ('$JS.API.STREAM.INFO.' + $s),
    ('$JS.API.CONSUMER.CREATE.' + $s),
    ('$JS.API.CONSUMER.CREATE.' + $s + '.>'),
    ('$JS.API.CONSUMER.INFO.' + $s + '.>'),
    ('$JS.API.CONSUMER.DELETE.' + $s + '.>'),
    ('$JS.API.DIRECT.GET.' + $s),
    ('$JS.API.DIRECT.GET.' + $s + '.>'),
    ('$JS.API.STREAM.MSG.GET.' + $s)
  )
}
function Quote([string[]]$xs) { ($xs | ForEach-Object { '"' + $_ + '"' }) -join ", " }

function AgentUser([string]$id) {
  $pub = @(
    'a2a.v1.local.rpc.*.*',
    "a2a.v1.local.ev.$id.>",
    "a2a.v1.local.audit.$id",
    ('$KV.a2ab-local-cards.' + $id),
    ('$KV.a2ab-local-presence.' + $id),
    ('$KV.a2ab-local-claims.' + $id + '.*'),
    '$O.a2ab-local-artifacts.C.>',
    '$O.a2ab-local-artifacts.M.>'
  )
  foreach ($s in $readStreams) { $pub += ReadBundle $s }
  $sub = @("_INBOX.$id.>", "a2a.v1.local.rpc.$id.*")
  @"
    {
      nkey: "$(Pub $id)",
      permissions: {
        publish: { allow: [ $(Quote $pub) ] }
        subscribe: { allow: [ $(Quote $sub) ] }
        allow_responses: { max: 1, expires: "2m" }
      }
    }
"@
}

function OperatorUser([string]$id) {
  $pub = @('a2a.v1.local.rpc.*.*', "a2a.v1.local.audit.$id")
  foreach ($s in @("KV_a2ab-local-cards", "KV_a2ab-local-presence", "KV_a2ab-local-claims")) { $pub += ReadBundle $s }
  $sub = @("_INBOX.$id.>")
  @"
    {
      nkey: "$(Pub $id)",
      permissions: {
        publish: { allow: [ $(Quote $pub) ] }
        subscribe: { allow: [ $(Quote $sub) ] }
      }
    }
"@
}

$users = @(
  (AgentUser "omp"),
  (AgentUser "claude"),
  (OperatorUser "tui"),
  @"
    {
      nkey: "$(Pub "admin")",
      permissions: {
        publish: { allow: [ ">" ] }
        subscribe: { allow: [ ">" ] }
      }
    }
"@
) -join ",`n"

$conf = @"
# GENERATED by spikes/nats/gen-config.ps1. Public NKeys only.
host: "127.0.0.1"
port: 4222
server_name: "spike-local"
max_payload: $MaxPayload
jetstream {
  store_dir: "$store"
  max_memory_store: 268435456
  max_file_store: 4294967296
}
authorization {
  users: [
$users
  ]
}
"@
Set-Content -Path $Out -Value $conf -Encoding ascii
Write-Output "wrote $Out (max_payload=$MaxPayload)"
