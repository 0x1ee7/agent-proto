#!/usr/bin/env python3
"""hermes-a2a spike probe (stdlib only). Talks only to 127.0.0.1:9911 (the isolated gateway).

Reads peer tokens from .spikes/hermes/secrets/peer.token and peer2.token (generated by the
operator, never printed or copied). Writes .spikes/hermes/logs/probe-results.json with tokens
scrubbed and prints one summary line per test.

Usage: python spikes/hermes-a2a/probe.py
"""
import http.client as httpclient
import json
import pathlib
import socket
import time
import uuid

HOST, PORT = "127.0.0.1", 9911
ROOT = pathlib.Path(__file__).resolve().parents[2]
SECRETS = ROOT / ".spikes" / "hermes" / "secrets"
LOGS = ROOT / ".spikes" / "hermes" / "logs"
STUB_LOG = LOGS / "stub.jsonl"
OUT = LOGS / "probe-results.json"


def load_peer(path):
    name, _, token = path.read_text(encoding="utf-8").strip().partition(":")
    return name, token


PEER1_NAME, PEER1 = load_peer(SECRETS / "peer.token")
PEER2_NAME, PEER2 = load_peer(SECRETS / "peer2.token")
RESULTS = []


def scrub(text):
    for tok in (PEER1, PEER2):
        text = text.replace(tok, "<TOKEN>")
    return text


def record(tid, title, status, summary, detail=None):
    RESULTS.append({"id": tid, "title": title, "http": status, "summary": summary, "detail": detail})
    print(scrub(f"{tid} http={status} {summary}")[:300], flush=True)


def http(method, path, body=None, headers=None, timeout=60):
    conn = httpclient.HTTPConnection(HOST, PORT, timeout=timeout)
    try:
        conn.request(method, path, body=body, headers=headers or {})
        resp = conn.getresponse()
        return resp.status, dict(resp.getheaders()), resp.read().decode("utf-8", "replace")
    except socket.timeout:
        return "TIMEOUT", {}, ""
    except OSError as exc:
        return "CONN_ERR", {}, str(exc)
    finally:
        conn.close()


def rpc(method, params, token=PEER1, version="1.0", path="/", raw=None, req_id=None, extra=None, timeout=60):
    headers = {"Content-Type": "application/json"}
    if token is not None:
        headers["Authorization"] = "Bearer " + token
    if version is not None:
        headers["A2A-Version"] = version
    if raw is None:
        envelope = {"jsonrpc": "2.0", "id": req_id or uuid.uuid4().hex[:8], "method": method, "params": params}
        envelope.update(extra or {})
        raw = json.dumps(envelope).encode("utf-8")
    return http("POST", path, raw, headers, timeout)


def jparse(text):
    try:
        return json.loads(text)
    except ValueError:
        return None


def brief(text):
    obj = jparse(text)
    if obj is None:
        return "non-json: " + text[:120].replace("\n", " ")
    if "error" in obj:
        err = obj["error"]
        return f"error code={err.get('code')} reason={(err.get('data') or {}).get('reason') if isinstance(err.get('data'), dict) else ''} msg={str(err.get('message'))[:120]}"
    res = obj.get("result", obj)
    return "result keys=" + ",".join(sorted(res.keys())) if isinstance(res, dict) else "result=" + str(res)[:120]


def task_of(text):
    obj = jparse(text) or {}
    res = obj.get("result") or {}
    return res.get("task", res) if isinstance(res, dict) else {}


def task_brief(task):
    if not task:
        return "no task"
    st = (task.get("status") or {}).get("state")
    arts = [p.get("text", "") for a in task.get("artifacts", []) for p in a.get("parts", []) if isinstance(p, dict)]
    return f"id={task.get('id')} ctx={task.get('contextId')} state={st} artifacts={arts[:1]}"


def umsg(text, ctx=None, **extra):
    msg = {"messageId": uuid.uuid4().hex, "role": "ROLE_USER", "parts": [{"text": text}]}
    if ctx:
        msg["contextId"] = ctx
    msg.update(extra)
    return msg


def stub_lines():
    return STUB_LOG.read_text(encoding="utf-8").splitlines() if STUB_LOG.exists() else []


def sse_send(method, params, token=PEER1, timeout=60):
    """Read an SSE response frame by frame until ': done' or EOF."""
    conn = httpclient.HTTPConnection(HOST, PORT, timeout=timeout)
    body = json.dumps({"jsonrpc": "2.0", "id": "sse1", "method": method, "params": params}).encode("utf-8")
    headers = {"Content-Type": "application/json", "Accept": "text/event-stream",
               "Authorization": "Bearer " + token, "A2A-Version": "1.0"}
    frames, t0 = [], time.time()
    try:
        conn.request("POST", "/", body=body, headers=headers)
        resp = conn.getresponse()
        status, ctype = resp.status, resp.getheader("Content-Type")
        while True:
            line = resp.readline()
            if not line:
                frames.append((round(time.time() - t0, 2), "EOF"))
                break
            text = line.decode("utf-8", "replace").rstrip("\r\n")
            if text:
                frames.append((round(time.time() - t0, 2), text))
            if text == ": done":
                break
    except socket.timeout:
        frames.append((round(time.time() - t0, 2), "TIMEOUT"))
        status, ctype = "TIMEOUT", ""
    except OSError as exc:
        frames.append((round(time.time() - t0, 2), "CONN_ERR " + str(exc)))
        status, ctype = "CONN_ERR", ""
    finally:
        conn.close()
    return status, ctype, frames


def main():
    LOGS.mkdir(parents=True, exist_ok=True)
    ctx_a = "ctx-spike-" + uuid.uuid4().hex[:12]

    # Q2: card as served (both paths) and root/health routes.
    st, hd, card_txt = http("GET", "/.well-known/agent.json")
    (LOGS / "card-live.json").write_text(card_txt, encoding="utf-8")
    record("T01", "card /.well-known/agent.json", st, f"bytes={len(card_txt)} ctype={hd.get('Content-Type')}", card_txt[:1500])
    st2, _, card2 = http("GET", "/.well-known/agent-card.json")
    record("T02", "card /.well-known/agent-card.json", st2, f"same_as_T01={card2 == card_txt}")
    for path in ("/", "/health", "/metrics"):
        st, _, txt = http("GET", path)
        record("T03", f"GET {path} (no auth)", st, txt[:200].replace("\n", " "))

    # Q5 auth failures and Q6/Q3 happy path.
    st, _, txt = rpc("SendMessage", {"message": umsg("STUB_ECHO noauth")}, token=None)
    record("T04", "SendMessage no Authorization", st, brief(txt), txt[:400])
    st, _, txt = rpc("SendMessage", {"message": umsg("STUB_ECHO badauth")}, token="not-a-real-token")
    record("T05", "SendMessage wrong bearer token", st, brief(txt), txt[:400])
    st, _, txt = rpc("SendMessage", {"message": umsg("STUB_ECHO hello", ctx=ctx_a)})
    t1 = task_of(txt)
    record("T06", "SendMessage peer1 A2A-Version 1.0 (Q3 shape)", st, task_brief(t1) + " | " + brief(txt), txt[:1500])
    task1_id = t1.get("id", "")

    # Q5 version handling.
    st, _, txt = rpc("SendMessage", {"message": umsg("STUB_ECHO nover")}, version=None)
    record("T07", "SendMessage A2A-Version absent", st, brief(txt), txt[:300])
    st, _, txt = rpc("SendMessage", {"message": umsg("STUB_ECHO v03")}, version="0.3")
    record("T08", "SendMessage A2A-Version 0.3", st, brief(txt), txt[:300])
    st, _, txt = rpc("SendMessage", {"message": umsg("STUB_ECHO v100")}, version="1.0.0")
    record("T09", "SendMessage A2A-Version 1.0.0", st, task_brief(task_of(txt)) or brief(txt), txt[:300])

    # Q5 method/param errors.
    st, _, txt = rpc("Frobnicate", {})
    record("T10", "unknown method Frobnicate", st, brief(txt), txt[:300])
    st, _, txt = rpc("GetTask", {"id": "task-does-not-exist"})
    record("T11", "GetTask unknown id", st, brief(txt), txt[:300])
    st, _, txt = rpc("CancelTask", {"id": "task-does-not-exist"})
    record("T12", "CancelTask unknown id", st, brief(txt), txt[:300])
    st, _, txt = rpc(None, None, raw=b"{")
    record("T13", "malformed JSON body", st, brief(txt), txt[:300])
    big = b'{"jsonrpc":"2.0","id":1,"method":"SendMessage","params":{"x":"' + b"a" * 1048577 + b'"}}'
    st, _, txt = rpc(None, None, raw=big)
    record("T14", "body > 1 MiB", st, brief(txt) if st != "CONN_ERR" else "CONN_ERR (server closed early)", txt[:200])
    st, _, txt = rpc(None, None, raw=b"[]")
    record("T15", "JSON array body", st, brief(txt), txt[:300])
    st, _, txt = rpc("SendMessage", "not-an-object")
    record("T16", "params is a string", st, brief(txt), txt[:300])

    # Q3 SSE frames.
    st, ctype, frames = sse_send("SendStreamingMessage", {"message": umsg("STUB_ECHO stream hi")})
    record("T17", "SendStreamingMessage SSE frames", st, f"ctype={ctype} frames={len(frames)} last={frames[-1][1] if frames else None}",
           [{"t": t, "line": line[:300]} for t, line in frames])

    # Q4 INPUT_REQUIRED inbound.
    st, _, txt = rpc("SendMessage", {"message": umsg("STUB_INPUT_REQUIRED which city")})
    t4 = task_of(txt)
    record("T18", "SendMessage STUB_INPUT_REQUIRED (Q4)", st, task_brief(t4), txt[:1200])

    # Tasks listing and baseline GetTask.
    st, _, txt = rpc("ListTasks", {})
    record("T19", "ListTasks peer1", st, brief(txt), txt[:600])
    st, _, txt = rpc("GetTask", {"id": task1_id})
    record("T20", "GetTask own task (peer1)", st, task_brief(task_of(txt)) or brief(txt), txt[:600])

    # Q6 contextId reuse by a different peer, and cross-peer task access.
    before = len(stub_lines())
    st, _, txt = rpc("SendMessage", {"message": umsg("STUB_ECHO from peer2", ctx=ctx_a)}, token=PEER2)
    t21 = task_of(txt)
    new_stub = stub_lines()[before:]
    stub_info = [json.loads(line) for line in new_stub if line.strip()]
    record("T21", "peer2 reuses peer1 contextId (Q6)", st, task_brief(t21) + " | " + brief(txt),
           {"response": txt[:900], "stub_requests": [{"n_messages": s.get("n_messages"), "roles": s.get("roles"),
                                                     "last_user_head": s.get("last_user_head")} for s in stub_info]})
    st, _, txt = rpc("GetTask", {"id": task1_id}, token=PEER2)
    record("T22", "peer2 GetTask on peer1 taskId (Q6)", st, task_brief(task_of(txt)) or brief(txt), txt[:600])
    st, _, txt = rpc("CancelTask", {"id": task1_id}, token=PEER2)
    record("T23", "peer2 CancelTask on peer1 taskId (Q6)", st, brief(txt), txt[:600])
    st, _, txt = rpc("ListTasks", {}, token=PEER2)
    seen = [t.get("id") for t in (jparse(txt) or {}).get("result", {}).get("tasks", [])] if jparse(txt) else []
    record("T24", "ListTasks peer2 (does it list peer1 task?)", st, f"count={len(seen)} includes_peer1_task={task1_id in seen}", seen[:20])

    # Q5 empty text, Q7 unknown fields, tenant handling.
    st, _, txt = rpc("SendMessage", {"message": umsg("")})
    record("T25", "SendMessage empty text", st, task_brief(task_of(txt)) or brief(txt), txt[:500])
    st, _, txt = rpc("SendMessage", {"message": umsg("STUB_ECHO unknown fields", **{"x-unknown-field": {"a": 1}})},
                     extra=None)
    record("T26", "unknown message field (Q7)", st, task_brief(task_of(txt)) or brief(txt), txt[:500])
    body = {"jsonrpc": "2.0", "id": "u1", "method": "SendMessage",
            "params": {"message": umsg("STUB_ECHO unknown params"), "futureParam": {"b": 2},
                       "configuration": {"acceptedOutputModes": ["text/plain"], "unknownCfg": True}},
            "unknownEnvelope": True}
    st, _, txt = rpc(None, None, raw=json.dumps(body).encode("utf-8"))
    record("T27", "unknown envelope/params fields (Q7)", st, task_brief(task_of(txt)) or brief(txt), txt[:500])
    st, _, txt = rpc("SendMessage", {"message": umsg("STUB_ECHO tenant other"), "tenant": "other"})
    record("T28", "params.tenant='other' on default agent", st, task_brief(task_of(txt)) or brief(txt), txt[:500])
    st, _, txt = rpc("SendMessage", {"message": umsg("STUB_ECHO tenant local"), "tenant": "local"})
    record("T29", "params.tenant='local' on default agent", st, task_brief(task_of(txt)) or brief(txt), txt[:300])

    # Q5 rate limit (per peer identity): peer2 blasts cheap calls.
    codes = []
    for _ in range(70):
        st, _, txt = rpc("ListTasks", {}, token=PEER2)
        codes.append(st)
    first_429 = codes.index(429) + 1 if 429 in codes else None
    record("T30", "rate limit peer2 (70 x ListTasks)", "429" if first_429 else "none",
           f"first_429_at={first_429} total_429={codes.count(429)} statuses={sorted(set(map(str, codes)))}", None)
    st, _, txt = rpc("ListTasks", {}, token=PEER1)
    record("T31", "peer1 unaffected after peer2 rate limit", st, brief(txt))
    st, _, txt = http("GET", "/metrics")
    record("T32", "GET /metrics after tests", st, txt[:600].replace("\n", " "))

    OUT.write_text(scrub(json.dumps({"results": RESULTS, "task1_id": task1_id, "ctx_a": ctx_a}, indent=2, ensure_ascii=False)),
                   encoding="utf-8")
    print("wrote", OUT.relative_to(ROOT), "tests=", len(RESULTS), flush=True)


if __name__ == "__main__":
    main()
